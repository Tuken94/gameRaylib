const char* ARCHIVO_ESCENARIO="textures/32rogues/tiles.png";
Texture2D textura_escenario;
const Rectangle LOSAS[5]={
    (Rectangle){0,0,0,0},//este no se va a usar
    (Rectangle){0,0,32,32},
    (Rectangle){32,0,32,32},
    (Rectangle){0,352,32,32},
    (Rectangle){224,512,32,32},
};

//Para guardar la cantidad de escaleras que hay y su posición
Vector2 escaleras[100];
int numEscaleras;


void EscenarioIniciar(){
    textura_escenario=LoadTexture(ARCHIVO_ESCENARIO);
    //Recopilación escaleras
    numEscaleras=0;
    for(int i=0;i<TERRENO_ALTO;i++){
        for(int j=0;j<TERRENO_ANCHO;j++){
            if(TERRENO[i][j]==4){
                escaleras[numEscaleras]=(Vector2){j,i};
                numEscaleras++;
            }
        }
    }
}

void EscenarioDibujar(Vector2 losaProta, int rangoH, int rangoV){
    int valorVerticalMinimo=(losaProta.y-rangoV<=0)?0:losaProta.y-rangoV;
    int valorVerticalMaximo=(losaProta.y+rangoV<=TERRENO_ALTO)?losaProta.y+rangoV:TERRENO_ALTO;
    int valorHorizontalMinimo=(losaProta.x-rangoH<=0)?0:losaProta.x-rangoH;
    int valorHorizontalMaximo=(losaProta.x+rangoH<=TERRENO_ANCHO)?losaProta.x+rangoH:TERRENO_ANCHO;
    for(int i=valorVerticalMinimo;i<valorVerticalMaximo;i++){
        for(int j=valorHorizontalMinimo;j<valorHorizontalMaximo;j++){
            int l=TERRENO[i][j];
            if(l>0){
                if(l==4){//Si es la escalera, pinta el suelo antes para que se vea superpuesto
                    DrawTextureRec(textura_escenario,LOSAS[3],(Vector2){j*ANCHO_LOSA,i*ALTO_LOSA},WHITE);
                }
                DrawTextureRec(textura_escenario,LOSAS[l],(Vector2){j*ANCHO_LOSA,i*ALTO_LOSA},WHITE);
            }
        }
    }
}

//Comprueba si la "nueva" posición del prota está libre o colisiona con una pared
bool UbicacionLibre(Rectangle r){
    //Si la esquina sup-izda del prota coincide con losa -> no se puede
    int destinoX=(int)(r.x/ANCHO_LOSA);
    int destinoY=(int)(r.y/ALTO_LOSA);
    if(TERRENO[destinoY][destinoX]!=3) return false;
    //Si la esquina sup-derecha del prota coincide con losa -> no se puede
    destinoX=(int)((r.x+r.width)/ANCHO_LOSA);
    if(TERRENO[destinoY][destinoX]!=3) return false;
    //Si la esquina inf-derecha del prota coincide con losa -> no se puede
    destinoY=(int)((r.y+r.height)/ALTO_LOSA);
    if(TERRENO[destinoY][destinoX]!=3) return false;
    //Si la esquina inf-izq del prota coincide con losa -> no se puede
    destinoX=(int)(r.x/ANCHO_LOSA);
    if(TERRENO[destinoY][destinoX]!=3) return false;

    return true;
}

//Devuelve una de las escaleras al azar
Vector2 EscaleraAleatoria(){
    return escaleras[GetRandomValue(0,numEscaleras-1)];
}






